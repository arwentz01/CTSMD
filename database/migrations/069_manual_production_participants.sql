SET NAMES utf8mb4;

CREATE TABLE manual_participants (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    display_name VARCHAR(190) NULL,
    biography TEXT NULL,
    headshot_stored_file_id BIGINT UNSIGNED NULL,
    private_notes TEXT NULL,
    status ENUM('active','archived','transferred') NOT NULL DEFAULT 'active',
    transferred_to_user_id BIGINT UNSIGNED NULL,
    transferred_at DATETIME NULL,
    created_by_user_id BIGINT UNSIGNED NOT NULL,
    updated_by_user_id BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_manual_participant_name (last_name,first_name),
    KEY idx_manual_participant_status (status),
    CONSTRAINT fk_manual_participant_headshot FOREIGN KEY (headshot_stored_file_id) REFERENCES stored_files(id) ON DELETE SET NULL,
    CONSTRAINT fk_manual_participant_transfer_user FOREIGN KEY (transferred_to_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_manual_participant_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_manual_participant_editor FOREIGN KEY (updated_by_user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE manual_participant_credits (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    manual_participant_id BIGINT UNSIGNED NOT NULL,
    production_id BIGINT UNSIGNED NOT NULL,
    participant_type ENUM('cast','crew','creative','other') NOT NULL DEFAULT 'cast',
    roles_json JSON NULL,
    role_title VARCHAR(500) NULL,
    casting_status ENUM('under_review','callback','offered','cast','not_cast','withdrawn') NOT NULL DEFAULT 'under_review',
    participation_track VARCHAR(100) NULL,
    display_order INT NOT NULL DEFAULT 0,
    staff_notes TEXT NULL,
    approve_public_name TINYINT(1) NOT NULL DEFAULT 0,
    approve_public_biography TINYINT(1) NOT NULL DEFAULT 0,
    approve_public_headshot TINYINT(1) NOT NULL DEFAULT 0,
    active TINYINT(1) NOT NULL DEFAULT 1,
    transferred_to_user_id BIGINT UNSIGNED NULL,
    transferred_at DATETIME NULL,
    created_by_user_id BIGINT UNSIGNED NOT NULL,
    updated_by_user_id BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_manual_participant_production (manual_participant_id,production_id),
    KEY idx_manual_credit_board (production_id,active,casting_status,display_order),
    CONSTRAINT fk_manual_credit_profile FOREIGN KEY (manual_participant_id) REFERENCES manual_participants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_manual_credit_production FOREIGN KEY (production_id) REFERENCES productions(id) ON DELETE CASCADE,
    CONSTRAINT fk_manual_credit_transfer_user FOREIGN KEY (transferred_to_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_manual_credit_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_manual_credit_editor FOREIGN KEY (updated_by_user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE playbill_manual_profiles (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    playbill_id BIGINT UNSIGNED NOT NULL,
    manual_credit_id BIGINT UNSIGNED NOT NULL,
    display_name VARCHAR(190) NOT NULL,
    role_title VARCHAR(500) NULL,
    participant_type ENUM('cast','crew','creative','other') NOT NULL DEFAULT 'cast',
    biography TEXT NULL,
    headshot_stored_file_id BIGINT UNSIGNED NULL,
    display_order INT NOT NULL DEFAULT 0,
    visible TINYINT(1) NOT NULL DEFAULT 0,
    approve_public_name TINYINT(1) NOT NULL DEFAULT 0,
    approve_public_biography TINYINT(1) NOT NULL DEFAULT 0,
    approve_public_headshot TINYINT(1) NOT NULL DEFAULT 0,
    updated_by_user_id BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_playbill_manual_profile (playbill_id,manual_credit_id),
    KEY idx_playbill_manual_public (playbill_id,visible,display_order),
    CONSTRAINT fk_playbill_manual_playbill FOREIGN KEY (playbill_id) REFERENCES playbills(id) ON DELETE CASCADE,
    CONSTRAINT fk_playbill_manual_credit FOREIGN KEY (manual_credit_id) REFERENCES manual_participant_credits(id) ON DELETE RESTRICT,
    CONSTRAINT fk_playbill_manual_headshot FOREIGN KEY (headshot_stored_file_id) REFERENCES stored_files(id) ON DELETE SET NULL,
    CONSTRAINT fk_playbill_manual_editor FOREIGN KEY (updated_by_user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
